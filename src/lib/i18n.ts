export function t(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const entry = D[key];
  let s = entry ? (lang === 'en' ? entry[1] : entry[0]) : key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}

